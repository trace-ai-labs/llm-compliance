"""Stage 1 — author scenario packs component-by-component (batched, resumable).

Each scenario is generated in SMALL, FOCUSED LLM calls instead of one
monolithic pack call, in dependency order:

  round 1   persona           system prompt + per-scenario hard directive
  round 2   task              T1 request + decision menu        (needs persona)
  round 3   rules             rule context                      (needs task)
            pressure.<key>    one call per scored pressure ×9   (needs task)
            guard_nonbinding  the one guard twin                (needs task)
  round 4   t2                pushback + challenge              (needs rules)
            attacks           both rule-scope add-ons           (needs rules +
                                                                 guard_nonbinding)

Every structurally-valid component then faces DUAL GUARD REVIEW: the two
--models that did NOT generate it each review it independently (so the trio
constantly cross-checks itself), failing it unless it is scoped to exactly
what that cell tests (nothing else leaking in) AND reads like something that
could actually have been written in that deployment. EITHER guard's FAIL
rejects the component and burns an attempt (guard disagreements are logged
for the κ analysis); on rejection, every failing guard's feedback goes
verbatim into the next generation attempt.
After --max-attempts (default 5) rejected attempts a component
becomes an NA placeholder, NA cascades to its dependents, the assembled
pack is saved FLAGGED (never counted valid) so the gap is visible, not
silent, and the component lands in results/benchmark/na_components.jsonl —
the worklist of what to regenerate later via --retry-na (which clears the
NA placeholders and their rejection history for a fresh set of attempts). Every review lands in results/benchmark/guard_log.jsonl as a flat
row (scenario, domain, component, pressure family, generator, guard, both
verdicts, agreement, feedback); `--guard-report` aggregates it by every
dimension and writes guard_report.csv + guard_agreement.csv (with per-pair
Cohen's κ) for the inter-annotator analysis.

EVERY model in `--models` authors its own COMPLETE pack for every scenario —
all 18 components by one model, so a data point is fully generated by a
single logged generator and the trio yields three independent packs per
scenario. The other trio models are that pack's guards; a rejected component
is regenerated by the SAME model with the guards' feedback folded in (the
generator fixes its own work, never a different model). Validated components
accumulate in results/benchmark/components/{sid}__{model}.json; when a
(scenario, generator) has all 18, they are assembled into the pack shape
items.py consumes and saved to results/benchmark/samples/{sid}__{model}.json
for human review. Rerunning the command regenerates only missing/invalid
components.

To redo one pack, delete its files and rerun:
results/benchmark/components/{sid}__{model}.json and
results/benchmark/samples/{sid}__{model}.json.

Usage:
  python -m src.benchmark.generate                 # generate everything missing
  python -m src.benchmark.generate --only aml_kyc.A moderation.B
  python -m src.benchmark.generate --models gemini kimi deepseek --workers 8
  python -m src.benchmark.generate --status        # validation report only
"""

