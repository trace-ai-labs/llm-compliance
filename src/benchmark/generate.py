# Report figure style: one measure per chart, one hue per measure (sequential
# rule), counts and values as ink-colored direct labels, recessive grid.
_FIG_BLUE = "#2563eb"    # pass rate bars
_FIG_RED = "#dc2626"     # NA / failure status (labeled, never color-alone)
_FIG_INK = "#1f2937"
_FIG_MUTED = "#6b7280"


def guard_figures(log_path: str = GUARD_LOG,
                  out_dir: str = os.path.join("results", "benchmark",
                                              "figures")) -> None:
    """Render the quality-report figures from guard_log.jsonl: pass rates by
    guard / generator / component kind / pressure family, guard-pair
    agreement (κ annotated), and attempts-to-acceptance."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        raise SystemExit("pip install matplotlib to render figures")
    from src.benchmark.judges import cohen_kappa

    rows = load_guard_log(log_path)
    judged = [r for r in rows if r["verdict"] in ("PASS", "FAIL")]
    if not judged:
        raise SystemExit(f"{log_path} has no judged reviews")
    os.makedirs(out_dir, exist_ok=True)

    def _barh(fname: str, title: str, agg: Dict[str, Tuple[int, int]]) -> None:
        names = sorted(agg, key=lambda k: agg[k][1] / agg[k][0])
        rates = [agg[n][1] / agg[n][0] for n in names]
        fig, ax = plt.subplots(figsize=(7.5, 0.62 * len(names) + 1.2))
        ax.barh(names, rates, height=0.55, color=_FIG_BLUE)
        for i, n in enumerate(names):
            total, p = agg[n]
            ax.text(rates[i] + 0.015, i, f"{rates[i]:.0%}  (n={total})",
                    va="center", fontsize=9, color=_FIG_INK)
        ax.set_xlim(0, 1.18)
        ax.set_title(title, loc="left", fontsize=11, color=_FIG_INK, pad=10)
        ax.xaxis.set_major_formatter(lambda v, _: f"{v:.0%}")
        ax.tick_params(colors=_FIG_INK, labelsize=9)
        ax.grid(axis="x", color="#e5e7eb", linewidth=0.8)
        ax.set_axisbelow(True)
        for s in ("top", "right", "left"):
            ax.spines[s].set_visible(False)
        ax.spines["bottom"].set_color("#e5e7eb")
        fig.tight_layout()
        fig.savefig(os.path.join(out_dir, fname), dpi=150)
        plt.close(fig)

    def _agg(keyfn) -> Dict[str, Tuple[int, int]]:
        out: Dict[str, List[int]] = {}
        for r in judged:
            a = out.setdefault(str(keyfn(r)), [0, 0])
            a[0] += 1
            a[1] += r["verdict"] == "PASS"
        return {k: (v[0], v[1]) for k, v in out.items()}

    _barh("guard_pass_by_guard.png", "Guard pass rate by guard model",
          _agg(lambda r: r["guard_model"]))
    _barh("guard_pass_by_generator.png", "Guard pass rate by generator model",
          _agg(lambda r: r["generator_model"]))
    _barh("guard_pass_by_component.png", "Guard pass rate by component type",
          _agg(lambda r: r["component_kind"]))
    _barh("guard_pass_by_pressure.png", "Guard pass rate by pressure family",
          _agg(lambda r: r["pressure_key"] or "(non-pressure)"))
    _barh("guard_pass_by_domain.png", "Guard pass rate by domain",
          _agg(lambda r: r["domain"]))

    # guard-pair agreement, κ annotated on each bar
    pairs: Dict[Tuple[str, str], Tuple[List[str], List[str]]] = {}
    for r in judged:
        if r["co_verdict"] not in ("PASS", "FAIL"):
            continue
        pair = tuple(sorted([r["guard_model"], r["co_guard_model"]]))
        a, b = pairs.setdefault(pair, ([], []))
        if r["guard_model"] == pair[0]:
            a.append(r["verdict"])
            b.append(r["co_verdict"])
    if pairs:
        names = [f"{p[0].split('/')[-1]}\n+ {p[1].split('/')[-1]}"
                 for p in sorted(pairs)]
        vals, notes = [], []
        for p in sorted(pairs):
            a, b = pairs[p]
            rate = sum(x == y for x, y in zip(a, b)) / len(a)
            kappa = cohen_kappa(a, b) if len(a) >= 2 else float("nan")
            vals.append(rate)
            notes.append(f"{rate:.0%}  κ={kappa:.2f}  (n={len(a)})")
        fig, ax = plt.subplots(figsize=(7.5, 0.9 * len(names) + 1.2))
        ax.barh(names, vals, height=0.55, color=_FIG_BLUE)
        for i, note in enumerate(notes):
            ax.text(vals[i] + 0.015, i, note, va="center", fontsize=9,
                    color=_FIG_INK)
        ax.set_xlim(0, 1.3)
        ax.set_title("Guard-pair agreement (Cohen's κ annotated)", loc="left",
                     fontsize=11, color=_FIG_INK, pad=10)
        ax.xaxis.set_major_formatter(lambda v, _: f"{v:.0%}")
        ax.tick_params(colors=_FIG_INK, labelsize=9)
        ax.grid(axis="x", color="#e5e7eb", linewidth=0.8)
        ax.set_axisbelow(True)
        for s in ("top", "right", "left"):
            ax.spines[s].set_visible(False)
        ax.spines["bottom"].set_color("#e5e7eb")
        fig.tight_layout()
        fig.savefig(os.path.join(out_dir, "guard_agreement.png"), dpi=150)
        plt.close(fig)

    # attempts consumed per component: accepted at the k-th attempt of this
    # log (attempt ids are lifetime counters, so normalize per component)
    first_attempt: Dict[Tuple[str, str], int] = {}
    accepted_raw: Dict[Tuple[str, str], int] = {}
    rejected_n: Counter = Counter()
    for r in judged:
        key = (r["scenario_id"], r["component"])
        first_attempt[key] = min(first_attempt.get(key, 10 ** 9), r["attempt"])
        if r["accepted"]:
            accepted_raw[key] = min(accepted_raw.get(key, 10 ** 9), r["attempt"])
    accepted_at = {k: v - first_attempt[k] + 1 for k, v in accepted_raw.items()}
    for r in judged:
        key = (r["scenario_id"], r["component"])
        if key not in accepted_at and r["verdict"] == "FAIL":
            rejected_n[key] += 1
    if accepted_at or rejected_n:
        dist = Counter(accepted_at.values())
        labels = [str(k) for k in sorted(dist)] + (["NA"] if rejected_n else [])
        counts = [dist[k] for k in sorted(dist)] + \
                 ([len(rejected_n)] if rejected_n else [])
        colors = [_FIG_BLUE] * len(dist) + ([_FIG_RED] if rejected_n else [])
        fig, ax = plt.subplots(figsize=(6.5, 3.6))
        ax.bar(labels, counts, width=0.55, color=colors)
        for i, c in enumerate(counts):
            ax.text(i, c + 0.15, str(c), ha="center", fontsize=9,
                    color=_FIG_INK)
        ax.set_title("Generation attempts until guard acceptance "
                     "(NA = never accepted)", loc="left", fontsize=11,
                     color=_FIG_INK, pad=10)
        ax.set_xlabel("attempts consumed", fontsize=9, color=_FIG_MUTED)
        ax.tick_params(colors=_FIG_INK, labelsize=9)
        ax.grid(axis="y", color="#e5e7eb", linewidth=0.8)
        ax.set_axisbelow(True)
        for s in ("top", "right", "left"):
            ax.spines[s].set_visible(False)
        ax.spines["bottom"].set_color("#e5e7eb")
        fig.tight_layout()
        fig.savefig(os.path.join(out_dir, "guard_attempts.png"), dpi=150)
        plt.close(fig)

    # attempts-to-acceptance distribution, broken out BY component type
    def _kind(comp: str) -> str:
        return "pressure" if comp.startswith("pressure.") else comp
    acc_by_kind: Dict[str, List[int]] = {}
    na_by_kind: Counter = Counter()
    for (sid, comp), n in accepted_at.items():
        acc_by_kind.setdefault(_kind(comp), []).append(n)
    for (sid, comp) in rejected_n:
        na_by_kind[_kind(comp)] += 1
    _order = ["persona", "task", "rules", "t2", "guard_nonbinding", "attacks",
              "pressure"]
    kinds = [k for k in _order if k in acc_by_kind] + \
            [k for k in sorted(acc_by_kind) if k not in _order]
    if kinds:
        maxk = max((max(v) for v in acc_by_kind.values()), default=1)
        fig, axes = plt.subplots(len(kinds), 1,
                                 figsize=(6.5, 1.35 * len(kinds) + 0.6),
                                 sharex=True)
        if len(kinds) == 1:
            axes = [axes]
        for ax, k in zip(axes, kinds):
            vals = acc_by_kind[k]
            counts = [vals.count(i) for i in range(1, maxk + 1)]
            ax.bar(range(1, maxk + 1), counts, width=0.7, color=_FIG_BLUE)
            for i, c in enumerate(counts, start=1):
                if c:
                    ax.text(i, c, str(c), ha="center", va="bottom",
                            fontsize=8, color=_FIG_INK)
            mean = sum(vals) / len(vals)
            first = 100 * vals.count(1) / len(vals)
            na = na_by_kind[k]
            ax.set_title(f"{k}  -  n={len(vals)}, mean {mean:.2f} attempts, "
                         f"{first:.0f}% first-try, NA={na}",
                         loc="left", fontsize=9.5, color=_FIG_INK)
            ax.set_ylabel("packs", fontsize=8, color=_FIG_MUTED)
            ax.set_xticks(range(1, maxk + 1))
            ax.tick_params(colors=_FIG_INK, labelsize=8)
            ax.grid(axis="y", color="#e5e7eb", linewidth=0.8)
            ax.set_axisbelow(True)
            for s in ("top", "right", "left"):
                ax.spines[s].set_visible(False)
            ax.spines["bottom"].set_color("#e5e7eb")
        axes[-1].set_xlabel("attempts to acceptance (1 = passed first try)",
                            fontsize=9, color=_FIG_MUTED)
        fig.suptitle("Attempts to converge by component type", x=0.02,
                     ha="left", fontsize=11, color=_FIG_INK)
        fig.tight_layout(rect=[0, 0, 1, 0.99])
        fig.savefig(os.path.join(out_dir, "convergence_by_component.png"),
                    dpi=150)
        plt.close(fig)

    # attempts until each GUARD first passes a component, broken out by guard
    # (this is the per-guard strictness signal: who drags convergence)
    gfp: Dict[Tuple[str, str, str], int] = {}
    for r in judged:
        if r["verdict"] == "PASS":
            key = (r["scenario_id"], r["component"], r["guard_model"])
            norm = r["attempt"] - first_attempt[(r["scenario_id"],
                                                 r["component"])] + 1
            gfp[key] = min(gfp.get(key, 10 ** 9), norm)
    gfp_by_guard: Dict[str, List[int]] = {}
    for (sid, comp, gm), n in gfp.items():
        gfp_by_guard.setdefault(gm, []).append(n)
    guards = sorted(gfp_by_guard,
                    key=lambda g: sum(gfp_by_guard[g]) / len(gfp_by_guard[g]))
    if guards:
        maxk = max((max(v) for v in gfp_by_guard.values()), default=1)
        fig, axes = plt.subplots(len(guards), 1,
                                 figsize=(6.5, 1.35 * len(guards) + 0.6),
                                 sharex=True)
        if len(guards) == 1:
            axes = [axes]
        for ax, gm in zip(axes, guards):
            vals = gfp_by_guard[gm]
            counts = [vals.count(i) for i in range(1, maxk + 1)]
            ax.bar(range(1, maxk + 1), counts, width=0.7, color=_FIG_BLUE)
            for i, c in enumerate(counts, start=1):
                if c:
                    ax.text(i, c, str(c), ha="center", va="bottom",
                            fontsize=8, color=_FIG_INK)
            mean = sum(vals) / len(vals)
            first = 100 * vals.count(1) / len(vals)
            ax.set_title(f"{gm.split('/')[-1]}  -  n={len(vals)}, "
                         f"mean {mean:.2f} rounds to first PASS, "
                         f"{first:.0f}% first-try",
                         loc="left", fontsize=9.5, color=_FIG_INK)
            ax.set_ylabel("reviews", fontsize=8, color=_FIG_MUTED)
            ax.set_xticks(range(1, maxk + 1))
            ax.tick_params(colors=_FIG_INK, labelsize=8)
            ax.grid(axis="y", color="#e5e7eb", linewidth=0.8)
            ax.set_axisbelow(True)
            for s in ("top", "right", "left"):
                ax.spines[s].set_visible(False)
            ax.spines["bottom"].set_color("#e5e7eb")
        axes[-1].set_xlabel("attempts until this guard first passes",
                            fontsize=9, color=_FIG_MUTED)
        fig.suptitle("Attempts to satisfy each guard (per-guard strictness)",
                     x=0.02, ha="left", fontsize=11, color=_FIG_INK)
        fig.tight_layout(rect=[0, 0, 1, 0.99])
        fig.savefig(os.path.join(out_dir, "convergence_by_guard.png"), dpi=150)
        plt.close(fig)

        # aggregate: mean rounds-to-first-pass per guard
        agg = {g: (len(gfp_by_guard[g]),
                   sum(gfp_by_guard[g]) / len(gfp_by_guard[g])) for g in guards}
        names = sorted(agg, key=lambda k: agg[k][1])
        means = [agg[n][1] for n in names]
        fig, ax = plt.subplots(figsize=(7.5, 0.62 * len(names) + 1.2))
        ax.barh([n.split("/")[-1] for n in names], means, height=0.55,
                color=_FIG_BLUE)
        for i, n in enumerate(names):
            ax.text(means[i] + 0.03, i,
                    f"{means[i]:.2f} rounds  (n={agg[n][0]})",
                    va="center", fontsize=9, color=_FIG_INK)
        ax.set_xlim(0, maxk + 1)
        ax.set_title("Mean rounds to satisfy each guard (aggregate)",
                     loc="left", fontsize=11, color=_FIG_INK, pad=10)
        ax.tick_params(colors=_FIG_INK, labelsize=9)
        ax.grid(axis="x", color="#e5e7eb", linewidth=0.8)
        ax.set_axisbelow(True)
        for s in ("top", "right", "left"):
            ax.spines[s].set_visible(False)
        ax.spines["bottom"].set_color("#e5e7eb")
        fig.tight_layout()
        fig.savefig(os.path.join(out_dir, "convergence_mean_by_guard.png"),
                    dpi=150)
        plt.close(fig)

    # pack completeness: how many of each pack's components survived review.
