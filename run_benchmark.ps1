# PACT v1 — full pipeline runner (PowerShell 5.1 compatible).
#
# Requires BASETEN_API_KEY in .env (all calls go through the OpenAI SDK
# against https://inference.baseten.co/v1; see src/benchmark/batch.py).
#
# Typical full flow, in order:
#   .\run_benchmark.ps1 -Clean            # wipe ALL past generation/guard data
#   .\run_benchmark.ps1 -Generate         # stage 1: 48 x 3 packs (every model authors every scenario)
#   .\run_benchmark.ps1 -Report           # generation quality: stats, guard report, figures
#   .\run_benchmark.ps1 -Items            # stage 2: freeze items_v1.jsonl (commit the sha!)
#   .\run_benchmark.ps1 -Eval -EvalModels glm,deepseek,ultra -Reps 10
#   .\run_benchmark.ps1 -Judges           # honesty labels + awareness probe + blind CSVs
#   .\run_benchmark.ps1 -Aggregate        # Metrics 2.0 tables + gates
#   .\run_benchmark.ps1 -Publish          # local HF build; add -PushRepo you/pact-v1
#
# Every stage is resumable: killed runs continue with the same command.

param(
    [switch]$Clean,          # delete ALL results/benchmark data (fresh guard log etc.)
    [switch]$Generate,       # stage 1: generate scenario packs (trio cross-check)
    [switch]$Report,         # generation-quality stats + guard report + figures
    [switch]$Items,          # stage 2: render + freeze the 1872-item set
    [switch]$Eval,           # stage 3: run models under test over the items
    [switch]$Judges,         # stage 4: honesty labels, awareness probe, blind CSVs
    [switch]$Aggregate,      # stage 5: Metrics 2.0 axes, rollup, gates
    [switch]$Publish,        # stage 6: HF dataset build (local)
    [string[]]$GenModels = @("glm", "kimi", "ultra"),  # generator trio: each
                             # model authors a COMPLETE pack per scenario; the
                             # other two review every component of it
    [string[]]$EvalModels = @("glm", "deepseek", "ultra", "gptoss", "nemotron",
                              "trivial:always_comply", "trivial:always_cheapest",
                              "trivial:always_escalate", "trivial:random"),
    [int]$Reps = 10,         # reps per (item, arm); spec budget is 10
    [int]$Workers = 8,
    [string]$PushRepo = ""   # HF repo id to push to (needs HF_TOKEN + `pip install datasets`)
)

$ErrorActionPreference = "Stop"

if ($Clean) {
    # Full reset so a fresh run's guard/agreement data is not polluted by past
    # iterations: packs, components, raw call log, guard log, pipeline flags,
    # figures, reports, items, trials, judge outputs, HF build - everything.
    Remove-Item results\benchmark -Recurse -Force -Confirm:$false -ErrorAction SilentlyContinue
    New-Item -ItemType Directory -Force results\benchmark | Out-Null
    Write-Host "cleared results/benchmark (all past generation + guard data)"
}

if ($Generate) {
    # Stage 1: component-by-component generation. EVERY trio model authors its
    # own complete pack for every scenario (a data point is fully generated by
    # one logged model); the other two review each component (scope +
    # authenticity). Either guard's FAIL burns one attempt and feeds that
    # guard's feedback into the SAME generator's retry. Attempt budget is 8 for
    # the spine (persona/task/rules) and 4 for each add-on (pressure/guard/t2/
    # attacks); a spine NA drops the pack, an add-on NA just drops its cell(s)
    # and the pack still ships as a partial (x/n) sample. Unavailable calls
    # retry 3x then land in pipeline_flags.jsonl.
    # Packs -> results/benchmark/samples/{scenario}__{model}.json.
    python -m src.benchmark.generate --models @($GenModels) --workers $Workers
    # Reviewable artifacts: results/benchmark/samples/*.json (edit/delete a
    # pack's samples+components JSON and rerun to regenerate it).
    # Components that exhaust their 5 attempts land in
    # results/benchmark/na_components.jsonl (the rerun worklist); retry them
    # later with: python -m src.benchmark.generate --retry-na [--only <sid>]
    python -m src.benchmark.generate --status
}

if ($Report) {
    # Generation-quality reporting for the paper: call accounting, guard pass
    # rates by every dimension (guard/generator/domain/scenario/component/
    # pressure), guard-pair agreement + Cohen's kappa, and PNG figures.
    python -m src.benchmark.generate --stats
    python -m src.benchmark.generate --guard-report --figures
    Write-Host "CSVs: results/benchmark/guard_report.csv, guard_agreement.csv"
    Write-Host "figures: results/benchmark/figures/*.png"
}

if ($Items) {
    # Stage 2: deterministic render of the frozen item set: 13 cells per
    # (scenario x generator) pack = 48 x 3 x 13 = 1872 with the trio.
    # COMMIT items_v1.jsonl's sha256 before running any model - that commit is
    # the pre-registration.
    # Human review first: python -m src.benchmark.items --preview [--allow-partial]
    #   -> results/benchmark/items_preview.md (every rendered cell, markdown)
    python -m src.benchmark.items
}

if ($Eval) {
    # Stage 3: run the models under test. Two turns, both arms
    # (base / anti_adversarial), deterministic-first judging with LLM
    # fallback. trivial:* agents are the free gameability rows.
    # Cost note: |items| x 2 arms x $Reps reps x N models, ~2 calls/trial.
    python -m src.benchmark.runner --models @($EvalModels) --reps $Reps --workers $Workers
    # Power gate top-up after the grid (floor cells to n>=50):
    #   python -m src.benchmark.runner --models <model> --top-up-floor 50
}

if ($Judges) {
    # Stage 4: post-hoc judging over stored trials.
    python -m src.benchmark.judges classify-honesty --workers $Workers
    python -m src.benchmark.judges sample-honesty -n 60          # blind CSV for human kappa
    python -m src.benchmark.awareness -n 40 --workers $Workers   # eval-awareness probe
    python -m src.benchmark.awareness --sample-csv results\benchmark\awareness_annotation.csv
    # Judge-swap release gate (rerun outcome judging with an alternate judge;
    # Kendall tau >= 0.9 over model rankings must hold):
    #   python -m src.benchmark.judges judge-swap --judge-model k2.5
}

if ($Aggregate) {
    # Stage 5: the six Metrics 2.0 axes per model, cross-fitted CVaR rollup
    # with two-stage bootstrap CIs, BH-corrected contrasts, per-cell Wilson
    # CIs, promotion + power gates, gameability check.
    python -m src.benchmark.aggregate
    Write-Host "outputs: results/benchmark/metrics_v2.csv|.md, cells_v2.csv, contrasts_v2.csv"
}

if ($Publish) {
    # Stage 6: Hugging Face export - flat typed columns, per-split JSONL, and
    # the dataset card. Private holdout is EXCLUDED unless --include-private.
    if ($PushRepo) {
        python -m src.benchmark.publish --push $PushRepo
    } else {
        python -m src.benchmark.publish
    }
    Write-Host "local build: results/benchmark/hf/ (README.md is the dataset card)"
}

if (-not ($Clean -or $Generate -or $Report -or $Items -or $Eval -or $Judges -or $Aggregate -or $Publish)) {
    Write-Host "No stage selected. Stages, in order:"
    Write-Host "  -Clean      wipe all past data (do this before a fresh generation run)"
    Write-Host "  -Generate   stage 1: packs (trio generate + dual-guard review)"
    Write-Host "  -Report     generation-quality stats/report/figures"
    Write-Host "  -Items      stage 2: freeze the item set (commit the sha)"
    Write-Host "  -Eval       stage 3: run models under test (-EvalModels, -Reps)"
    Write-Host "  -Judges     stage 4: honesty/awareness judging + blind CSVs"
    Write-Host "  -Aggregate  stage 5: Metrics 2.0"
    Write-Host "  -Publish    stage 6: HF build (-PushRepo you/repo to upload)"
}
