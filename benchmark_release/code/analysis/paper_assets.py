def _tex_escape(s: str) -> str:
    """Escape LaTeX specials; U+2009 thin space becomes its LaTeX equivalent."""
    for a, b in (("\\", r"\textbackslash "), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("~", r"\textasciitilde "),
                 ("^", r"\textasciicircum "), (" ", r"\,")):
        s = s.replace(a, b)
    return s


def _tex_label(s: str) -> str:
    """Thin-space fix only, for labels that already carry LaTeX markup."""
    return s.replace(" ", r"\,")


